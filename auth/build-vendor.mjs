import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const directory = path.dirname(fileURLToPath(import.meta.url));
const runtime = ['@supabase/supabase-js', '@supabase/auth-js', '@supabase/functions-js', '@supabase/postgrest-js', '@supabase/realtime-js', '@supabase/phoenix', '@supabase/storage-js', 'iceberg-js', 'tslib'];
const notices = [];
for (const name of runtime) {
  const packageDirectory = path.join(directory, 'node_modules', name);
  const metadata = JSON.parse(await readFile(path.join(packageDirectory, 'package.json'), 'utf8'));
  let license;
  for (const filename of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'CopyrightNotice.txt']) {
    try { license = await readFile(path.join(packageDirectory, filename), 'utf8'); break; } catch {}
  }
  if (!license) throw new Error(`Missing license notice for ${name}`);
  notices.push(`${name}@${metadata.version} (${metadata.license})\n${license.trim()}`);
}
const result = await build({
  stdin: { contents: "export { createClient } from '@supabase/supabase-js';", resolveDir: directory, sourcefile: 'supabase-browser-entry.js' },
  bundle: true, platform: 'browser', format: 'iife', globalName: '__neuralBankSupabaseSDK',
  target: ['es2022'], minify: true, legalComments: 'inline', write: false,
});
const source = `/*\nGenerated by auth/build-vendor.mjs; official Supabase SDK, pinned in auth/package-lock.json.\n${notices.join('\n\n').replaceAll('*/', '* /')}\n*/\n${result.outputFiles[0].text}\nexport const createClient = __neuralBankSupabaseSDK.createClient;\n`;
if (/\bimport\s*(?:\(|\.)/.test(source) || /^\s*import\s/m.test(source)) throw new Error('Vendor bundle contains unsupported imports.');
new vm.Script(source.replace(/^export const createClient = /m, 'const createClient = '));
const destination = path.resolve(directory, '../src/vendor/supabase.js');
await mkdir(path.dirname(destination), { recursive: true });
await writeFile(destination, source);
console.log(`Bundled @supabase/supabase-js (${Buffer.byteLength(source)} bytes); ${runtime.length} license notices retained.`);
